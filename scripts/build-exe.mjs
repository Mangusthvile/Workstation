#!/usr/bin/env node
/**
 * Builds the double-click desktop app: release/Workstation.exe
 *
 *   npm run build:exe                         Windows x64 (default)
 *   npm run build:exe -- --target=bun-linux-x64   any Bun target, e.g. for testing
 *
 * Steps: Vite production build -> embed every file in dist/ into a TypeScript
 * module -> compile desktop/launcher.ts plus that module into one executable
 * with Bun (https://bun.sh). Bun can cross-compile, so a Windows exe can be
 * built on any OS. Requires `bun` on your PATH (install: npm i -g bun).
 */
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const arg = (name, fallback) => process.argv.find((a) => a.startsWith(`--${name}=`))?.split('=')[1] ?? fallback;
const target = arg('target', 'bun-windows-x64');
const isWindows = target.includes('windows');
const outfile = path.join(root, 'release', arg('outfile', isWindows ? 'Workstation.exe' : 'workstation'));

const run = (cmd, args) => {
  const result = spawnSync(cmd, args, { cwd: root, stdio: 'inherit', shell: process.platform === 'win32' });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
};

const bun = process.env.BUN || 'bun';
if (spawnSync(bun, ['--version'], { shell: process.platform === 'win32' }).status !== 0) {
  console.error('Bun is required to build the exe. Install it with "npm i -g bun" (or see https://bun.sh), then run this again.');
  process.exit(1);
}

console.log('1/3  Building the app (vite build)...');
run(process.platform === 'win32' ? 'npx.cmd' : 'npx', ['vite', 'build']);

console.log('2/3  Embedding dist/ into the launcher...');
const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.ico': 'image/x-icon',
  '.webp': 'image/webp',
  '.woff2': 'font/woff2',
  '.txt': 'text/plain; charset=utf-8',
};
const dist = path.join(root, 'dist');
const files = {};
const walk = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else {
      const urlPath = '/' + path.relative(dist, full).split(path.sep).join('/');
      files[urlPath] = {
        type: TYPES[path.extname(entry.name).toLowerCase()] ?? 'application/octet-stream',
        base64: fs.readFileSync(full).toString('base64'),
      };
    }
  }
};
walk(dist);

const buildDir = path.join(root, '.build');
fs.mkdirSync(buildDir, { recursive: true });
fs.writeFileSync(
  path.join(buildDir, 'embedded-dist.ts'),
  `// Generated by scripts/build-exe.mjs. Do not edit.\nimport type { EmbeddedFiles } from '../desktop/launcher';\n\nconst files: EmbeddedFiles = ${JSON.stringify(files)};\nexport default files;\n`
);
fs.writeFileSync(
  path.join(buildDir, 'entry.ts'),
  `// Generated by scripts/build-exe.mjs. Do not edit.\nimport files from './embedded-dist';\nimport { startDesktop } from '../desktop/launcher';\n\nstartDesktop(files);\n`
);
console.log(`     ${Object.keys(files).length} files embedded`);

console.log(`3/3  Compiling ${path.relative(root, outfile)} for ${target}...`);
fs.mkdirSync(path.dirname(outfile), { recursive: true });
run(bun, [
  'build',
  path.join(buildDir, 'entry.ts'),
  '--compile',
  `--target=${target}`,
  '--minify',
  '--define',
  'process.env.NODE_ENV="production"',
  '--outfile',
  outfile,
]);

const mb = (fs.statSync(outfile).size / 1024 / 1024).toFixed(1);
console.log(`\nDone: ${path.relative(root, outfile)} (${mb} MB)`);
